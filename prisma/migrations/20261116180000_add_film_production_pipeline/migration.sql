CREATE TABLE `film_productions` (
  `id` VARCHAR(191) NOT NULL,
  `projectId` VARCHAR(191) NOT NULL,
  `userId` VARCHAR(191) NOT NULL,
  `title` VARCHAR(191) NOT NULL,
  `format` VARCHAR(64) NOT NULL DEFAULT 'Short film',
  `genre` VARCHAR(191) NOT NULL DEFAULT '',
  `screenplay` LONGTEXT NOT NULL,
  `scenes` JSON NOT NULL,
  `settings` JSON NULL,
  `revision` INTEGER NOT NULL DEFAULT 1,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE INDEX `film_productions_projectId_key`(`projectId`),
  INDEX `film_productions_userId_updatedAt_idx`(`userId`, `updatedAt`),
  PRIMARY KEY (`id`),
  CONSTRAINT `film_productions_projectId_fkey` FOREIGN KEY (`projectId`) REFERENCES `projects`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `film_production_jobs` (
  `id` VARCHAR(191) NOT NULL,
  `productionId` VARCHAR(191) NOT NULL,
  `userId` VARCHAR(191) NOT NULL,
  `sceneId` VARCHAR(191) NOT NULL,
  `sceneTitle` VARCHAR(191) NOT NULL,
  `provider` VARCHAR(64) NOT NULL DEFAULT 'comfyui',
  `providerJobId` VARCHAR(191) NULL,
  `status` VARCHAR(32) NOT NULL DEFAULT 'queued',
  `progress` INTEGER NOT NULL DEFAULT 0,
  `prompt` LONGTEXT NOT NULL,
  `workflow` JSON NOT NULL,
  `outputs` JSON NULL,
  `failure` TEXT NULL,
  `attempt` INTEGER NOT NULL DEFAULT 0,
  `startedAt` DATETIME(3) NULL,
  `finishedAt` DATETIME(3) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX `film_production_jobs_userId_status_createdAt_idx`(`userId`, `status`, `createdAt`),
  INDEX `film_production_jobs_productionId_createdAt_idx`(`productionId`, `createdAt`),
  INDEX `film_production_jobs_providerJobId_idx`(`providerJobId`),
  PRIMARY KEY (`id`),
  CONSTRAINT `film_production_jobs_productionId_fkey` FOREIGN KEY (`productionId`) REFERENCES `film_productions`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
